import assert from 'node:assert/strict';
import {loadEnvFile} from 'node:process';
import {createClient} from '@supabase/supabase-js';
import {load} from '../tests/helpers.mjs';
loadEnvFile('.env.local');
const url=process.env.NEXT_PUBLIC_SUPABASE_URL;
if(!url||!['localhost','127.0.0.1'].includes(new URL(url).hostname))throw Error('Local Supabase only');
const options={auth:{persistSession:false,autoRefreshToken:false}};
const admin=createClient(url,process.env.SUPABASE_SECRET_KEY,options);
const anon=createClient(url,process.env.NEXT_PUBLIC_SUPABASE_PUBLISHABLE_KEY,options);
const {readWhimsy,saveWhimsyRecord,deleteWhimsyRecord}=load('lib/whimsy/persistence');
const {drawSix,questById,reference,selectQuest,rerollQuest,sealQuestWeek}=load('lib/whimsy/side-quests');
const {readQuestPreference,saveQuestPreference}=load('lib/whimsy/quest-preferences');
const id=()=>crypto.randomUUID(),users=[];
const must=result=>{if(result.error)throw result.error;return result.data;};
async function invite(){const link=must(await admin.auth.admin.generateLink({type:'invite',email:`side-quest-${id()}@example.test`}));users.push(link.user.id);const client=createClient(url,process.env.NEXT_PUBLIC_SUPABASE_PUBLISHABLE_KEY,options);const session=must(await client.auth.verifyOtp({type:'invite',token_hash:link.properties.hashed_token})).session;return {client,userId:link.user.id,session};}
async function save(client,record,expectedRevision=0,commandId=id()){return saveWhimsyRecord(client,'questWeeks',{record,expectedRevision,commandId});}
try{
 const a=await invite(),b=await invite();
 assert.equal((await readQuestPreference(a.client)).revision,0);
 const prefId=id(),savedPreference=await saveQuestPreference(a.client,{experience:'vibe',vibe:'Creative'},0,prefId);
 assert.equal(savedPreference.revision,1);
 assert.equal((await saveQuestPreference(a.client,{experience:'vibe',vibe:'Creative'},0,prefId)).revision,1);
 assert.equal((await readQuestPreference(b.client)).revision,0);
 await assert.rejects(()=>saveQuestPreference(a.client,{experience:'balance',vibe:'Cozy'},0,id()),e=>e.code==='40001');
 assert.equal((await readWhimsy(a.client)).questWeeks.length,0);
 assert.ok((await anon.rpc('read_whimsy')).error);
 const catalog=must(await a.client.from('whimsy_content_versions').select('content_id').eq('experience','side-quests').like('content_id','quest-%'));
 assert.equal(catalog.length,200);
 assert.ok((await anon.from('whimsy_content_versions').select('content_id')).error);
 const refs=drawSix({experience:'balance',vibe:'Cozy'},new Set(),()=>.4),now='2026-11-02T12:00:00Z';
 let week=await save(a.client,{id:id(),weekStart:'2026-11-02',timeZone:'America/Los_Angeles',draws:refs,activeIds:refs.map(r=>r.contentId),revealedIds:[],selectedIds:[],swaps:[]});
 assert.equal(week.revision,1);
 assert.equal((await readWhimsy(b.client)).questWeeks.length,0);
 await assert.rejects(()=>save(b.client,{...week,selectedIds:[refs[0].contentId]},week.revision),e=>e.code==='42501');
 week=await save(a.client,{...week,revealedIds:refs.map(r=>r.contentId)},week.revision);
 week=await save(a.client,selectQuest(week,refs[0].contentId),week.revision);
 week=await save(a.client,rerollQuest(week,refs[0].contentId,{experience:'balance',vibe:'Cozy'}),week.revision);
 assert.equal(week.selectedIds.length,0);
 for(const ref of refs.slice(1,4))week=await save(a.client,selectQuest(week,ref.contentId),week.revision);
 const beforeSeal=week.revision;week=await save(a.client,sealQuestWeek(week,now),week.revision);
 assert.equal(week.selectedIds.length,3);
 await assert.rejects(()=>save(a.client,{...week,selectedIds:[]},week.revision),e=>e.code==='22023');
 await assert.rejects(()=>save(a.client,{...week,selectedIds:[refs[1].contentId,refs[2].contentId,refs[4].contentId]},beforeSeal),e=>e.code==='40001');
 const quest=questById(week.selectedIds[0]);
 const completionId=id(),commandId=id(),completion={id:completionId,weekId:week.id,quest:reference(quest),category:quest.category,date:'2026-11-02',timeZone:week.timeZone,completedAt:now};
 const done=await saveWhimsyRecord(a.client,'questCompletions',{record:completion,expectedRevision:0,commandId});
 assert.equal((await saveWhimsyRecord(a.client,'questCompletions',{record:completion,expectedRevision:0,commandId})).id,done.id);
 const fresh=createClient(url,process.env.NEXT_PUBLIC_SUPABASE_PUBLISHABLE_KEY,options);
 must(await fresh.auth.setSession(a.session));
 assert.equal((await readQuestPreference(fresh)).vibe,'Creative');
 assert.equal((await readWhimsy(fresh)).questWeeks.find(w=>w.id===week.id)?.selectedIds.length,3);
 assert.equal((await readWhimsy(fresh)).questCompletions.length,1);
 await deleteWhimsyRecord(a.client,'questCompletions',done.id,done.revision,id());
 assert.equal((await readWhimsy(fresh)).questCompletions.length,0);
 const replacement=questById(drawSix({experience:'surprise',vibe:'Cozy'},new Set(week.draws.map(r=>r.contentId)))[0].contentId);
 week=await save(a.client,{...week,draws:[...week.draws,reference(replacement)],selectedIds:week.selectedIds.map((value,index)=>index===0?replacement.id:value),swaps:[...week.swaps,{from:quest.id,to:reference(replacement),at:now}]},week.revision);
 assert.equal((await readWhimsy(fresh)).questWeeks.find(w=>w.id===week.id)?.swaps.length,1);
 console.log('PASS 200 published quests, anonymous and cross-user isolation, draw/reveal/reroll/select/seal, conflict and invalid rewrite rejection, idempotent completion, undo, swap and fresh-client persistence');
}finally{for(const userId of users)must(await admin.auth.admin.deleteUser(userId));console.log('Disposable quest users removed; reference library retained.');}
